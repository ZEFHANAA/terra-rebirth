#!/usr/bin/env python3
"""Validate four subject banks and generate Godot question_bank.gd."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANK_DIR = Path('/home/ubuntu/.hermes/cache/scratch/bank')
BANKS = {
    'bd': ('bd.json', 'Basis Data'),
    'so': ('so.json', 'Sistem Operasi'),
    'kr': ('kr.json', 'Kriptografi'),
    'iot': ('iot.json', 'Internet of Things'),
}
rows = {}
for prefix, (filename, materi) in BANKS.items():
    data = json.loads((BANK_DIR / filename).read_text())
    if len(data) != 50:
        raise ValueError(f'{filename}: expected 50 rows, got {len(data)}')
    expected = [f'{prefix}-{i:02d}' for i in range(1, 51)]
    if [q.get('id') for q in data] != expected:
        raise ValueError(f'{filename}: IDs must be ordered {prefix}-01..{prefix}-50')
    for q in data:
        if len(q.get('options', [])) != 4 or len(set(q['options'])) != 4:
            raise ValueError(f"{q.get('id')}: expected four distinct options")
        if not isinstance(q.get('answer'), int) or not 0 <= q['answer'] <= 3:
            raise ValueError(f"{q.get('id')}: invalid answer index")
        if not q.get('prompt') or not q.get('explain'):
            raise ValueError(f"{q.get('id')}: prompt/explain missing")
    rows[materi] = data
(ROOT / 'data' / 'question_bank.gd').write_text(
    '## Generated by tools/gen_bank.py; edit source JSON banks, not this file.\n'
    'const BANK := ' + json.dumps(rows, ensure_ascii=False, indent='\t') + '\n'
)
total = sum(len(v) for v in rows.values())
print(f'validated {total} questions across {len(rows)} subjects')
